#!/usr/bin/env bash
# Flat sky130 filelists for reef_top (PD Drop 0): the vendored core filelist with Sram.v and
# ClockGate.sv swapped for the sky130 versions (rtl/sram, rtl/clock), then rtl/reef/reef.f.
# Paths use ${REEF_ROOT} (the directory holding rtl/: hw/ in LonghornSilicon/reef), so only one
# variable has to be set.
#
#   scripts/gen_filelists.sh           write configs/filelists/reef_top_sky130*.f
#   scripts/gen_filelists.sh --check   exit 1 if the committed files are stale (lint_reef.sh runs this)
#
# reef_top_sky130.f              Drop 0 synthesis: link sky130_fd_sc_hd and sram22_512x128m4w8 (SRAM22)
# reef_top_sky130_sim.f          Drop 0 Verilator: adds SRAM22's macro model, our model of the ICG
#                                cell, and upstream's verification/ assertions
# reef_top_sky130_openram{,_sim}.f  the same with the OpenRAM TCM (20 x sky130_sram_2kbyte_1rw1r_32x512_8,
#                                fallback; the sim list uses our cycle model of that macro)
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTDIR="$REPO_ROOT/configs/filelists"

flat() {  # core filelist, sram .f, clock .f
  echo "// Generated by scripts/gen_filelists.sh -- do not edit. Set REEF_ROOT to the hw/ directory (the one holding rtl/)."
  echo "// Core: rtl/vendor/coralnpu/$1 minus Sram.v and ClockGate.sv; sky130: rtl/sram/$2, rtl/clock/$3."
  grep -v '^//' "$REPO_ROOT/rtl/vendor/coralnpu/$1" | grep -v -e '/Sram\.v$' -e '/ClockGate\.sv$' \
    | sed 's|${CORALNPU_RTL}|${REEF_ROOT}/rtl/vendor/coralnpu|'
  grep -v '^//' "$REPO_ROOT/rtl/sram/$2"  | sed 's|${SRAM_RTL}|${REEF_ROOT}/rtl/sram|'
  grep -v '^//' "$REPO_ROOT/rtl/clock/$3" | sed 's|${CLOCK_RTL}|${REEF_ROOT}/rtl/clock|'
  grep -v '^//' "$REPO_ROOT/rtl/reef/reef.f" | sed 's|${REEF_RTL}|${REEF_ROOT}/rtl/reef|'
}

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
# name, core list, sram list, clock list, wrapper the list must contain
lists=(
  "reef_top_sky130.f         synth.f sram22.f      sky130.f     Sram_sram22.sv"
  "reef_top_sky130_sim.f     sim.f   sram22_sim.f  sky130_sim.f Sram_sram22.sv"
  "reef_top_sky130_openram.f     synth.f sky130.f     sky130.f     Sram_sky130.sv"
  "reef_top_sky130_openram_sim.f sim.f   sky130_sim.f sky130_sim.f Sram_sky130.sv"
)
names=()
for entry in "${lists[@]}"; do
  read -r f core sram clock wrapper <<< "$entry"
  names+=("$f")
  flat "$core" "$sram" "$clock" > "$tmp/$f"
  n_swap=$(grep -c -e '/Sram\.v$' -e '/ClockGate\.sv$' "$tmp/$f" || true)
  [ "$n_swap" = 0 ] || { echo "$f: vendored Sram.v/ClockGate.sv still listed" >&2; exit 1; }
  grep -q "/$wrapper\$" "$tmp/$f" && grep -q 'ClockGate_sky130.sv$' "$tmp/$f" \
    || { echo "$f: sky130 Sram ($wrapper)/ClockGate missing" >&2; exit 1; }
done

if [ "${1:-}" = --check ]; then
  for f in "${names[@]}"; do
    diff -q "$tmp/$f" "$OUTDIR/$f" >/dev/null 2>&1 \
      || { echo "configs/filelists/$f is stale: run scripts/gen_filelists.sh" >&2; exit 1; }
  done
  echo "filelists up to date"
else
  mkdir -p "$OUTDIR"
  for f in "${names[@]}"; do cp "$tmp/$f" "$OUTDIR/"; done
  wc -l "$OUTDIR"/reef_top_sky130*.f
fi
