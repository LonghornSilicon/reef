"""Generate includes/params.h from config/model.json and hardware.json.

The kernels, run_all.py and analysis/ all read these two JSON files, so C++
and Python share one source of truth. run_all.py regenerates the header on
every build; run by hand with `python config/gen_params.py`.
"""

import json
import math
from pathlib import Path

CONFIG = Path(__file__).resolve().parent
HEADER = CONFIG.parent / "includes" / "params.h"


def load() -> tuple[dict, dict]:
    """Return the parsed (model, hardware) configs."""
    model = json.loads((CONFIG / "model.json").read_text())
    hardware = json.loads((CONFIG / "hardware.json").read_text())
    return model, hardware


def derived(model: dict) -> dict[str, float]:
    """Scales the kernels take that follow from the base config."""
    m, q = model["model"], model["quant"]
    return {
        # GPT-2 scales scores by 1/sqrt(d_head); folded in here
        "score_scale": q["q_scale"] * q["k_scale"] / math.sqrt(m["d_head"]),
    }


def const(name: str) -> str:
    """Spell a snake_case key as the repo's kCamelCase constexpr name."""
    return "k" + "".join(part.capitalize() for part in name.split("_"))


def render(model: dict, hardware: dict) -> str:
    """Return the text of params.h."""
    lines = [
        "// params.h - GENERATED by config/gen_params.py from model.json and",
        "// hardware.json. Do not edit; change the JSON and regenerate.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace params {",
        "",
    ]

    def emit(name: str, value: float) -> None:
        if isinstance(value, bool):
            flag = "true" if value else "false"
            lines.append(f"constexpr bool {const(name)} = {flag};")
        elif isinstance(value, int):
            lines.append(f"constexpr size_t {const(name)} = {value};")
        else:
            lines.append(f"constexpr float {const(name)} = {value!r}F;")

    for key, value in model["model"].items():
        if key != "name":
            emit(key, value)
    lines.append("")
    for key, value in {**model["quant"], **derived(model)}.items():
        # zero points are signed offsets in kernel arithmetic
        if key.endswith("_zero"):
            lines.append(f"constexpr int32_t {const(key)} = {value};")
        else:
            emit(key, float(value))
    lines.append("")
    for kernel, shape in model["tiles"].items():
        if not kernel.startswith("_"):
            for dim, value in shape.items():
                emit(f"{kernel}_{dim}", value)
    lines.append("")
    for key, entry in hardware.items():
        value = entry.get("value") if isinstance(entry, dict) else None
        if isinstance(value, (bool, int)):
            emit(key, value)
    lines += ["", "} // namespace params", ""]
    return "\n".join(lines)


def main() -> None:
    """Write params.h if its contents changed."""
    text = render(*load())
    if not HEADER.exists() or HEADER.read_text() != text:
        HEADER.write_text(text)


if __name__ == "__main__":
    main()
