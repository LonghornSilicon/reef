"""Generate deterministic synthetic W8A8 fixtures with a PyTorch reference."""

import argparse
from pathlib import Path

import torch


def quantize(x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
    """Symmetric per-row INT8 rounding, including all-zero rows."""
    maximum = x.abs().amax(dim=-1)
    scale = torch.where(maximum == 0, 1.0, maximum / 127)
    return (x / scale[:, None]).round().clamp(-127, 127).to(torch.int8), scale


def main() -> None:
    """Write a C header with quantized inputs and expected intermediates."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--width", type=int, default=8)
    parser.add_argument("--hidden", type=int, default=16)
    parser.add_argument("--tokens", type=int, default=3)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if min(args.width, args.hidden, args.tokens) < 1:
        parser.error("dimensions must be positive")
    if max(args.width, args.hidden) >= 131072:
        parser.error("reduction widths must be below 131072")
    torch.set_num_threads(1)
    generator = torch.Generator().manual_seed(42)
    x = torch.randn(args.tokens, args.width, generator=generator) * 0.5
    x[-1] = 0
    w1 = torch.randn(args.hidden, args.width, generator=generator) * 0.15
    w2 = torch.randn(args.width, args.hidden, generator=generator) * 0.15
    w1[-1] = 0
    w2[-1] = 0
    b1 = torch.randn(args.hidden, generator=generator) * 0.05
    b2 = torch.randn(args.width, generator=generator) * 0.05
    qx, sx = quantize(x)
    q1, s1 = quantize(w1)
    q2, s2 = quantize(w2)
    a1 = qx.to(torch.int64) @ q1.to(torch.int64).T
    pre = a1.float() * sx[:, None] * s1[None, :] + b1
    hidden = (
        0.5
        * pre
        * (1 + torch.tanh(0.7978845608028654 * (pre + 0.044715 * pre**3)))
    )
    qh, sh = quantize(hidden)
    a2 = qh.to(torch.int64) @ q2.to(torch.int64).T
    output = a2.float() * sh[:, None] * s2[None, :] + b2
    # Independent floating matmul of dequantized operands, as in story_quality.
    fake_pre = (qx.float() * sx[:, None]) @ (q1.float() * s1[:, None]).T + b1
    torch.testing.assert_close(pre, fake_pre, atol=2e-6, rtol=2e-5)
    fake_hidden = (
        0.5
        * fake_pre
        * (
            1
            + torch.tanh(
                0.7978845608028654 * (fake_pre + 0.044715 * fake_pre**3)
            )
        )
    )
    fake_qh, fake_sh = quantize(fake_hidden)
    fake_out = (fake_qh.float() * fake_sh[:, None]) @ (
        q2.float() * s2[:, None]
    ).T + b2
    torch.testing.assert_close(output, fake_out, atol=2e-6, rtol=2e-5)
    arrays = {
        "input_fp32": x,
        "input_q": qx,
        "input_scale": sx,
        "w1": q1,
        "s1": s1,
        "b1": b1,
        "w2": q2,
        "s2": s2,
        "b2": b2,
        "expected_a1": a1,
        "expected_hidden": hidden,
        "expected_hidden_q": qh,
        "expected_hidden_scale": sh,
        "expected_a2": a2,
        "expected_output": output,
    }
    lines = [
        "// Generated by w8a8_mlp/main.py; seed 42; synthetic weights.",
        "#pragma once",
        "#include <stdint.h>",
        f"constexpr unsigned kTokens = {args.tokens};",
        f"constexpr unsigned kWidth = {args.width};",
        f"constexpr unsigned kHidden = {args.hidden};",
    ]
    for name, tensor in arrays.items():
        if tensor.is_floating_point():
            ctype = "float"
            values = [float(v).hex() + "f" for v in tensor.flatten()]
        else:
            ctype = "int8_t" if tensor.dtype == torch.int8 else "int32_t"
            values = [str(int(v)) for v in tensor.flatten()]
        lines.append(f"static const {ctype} {name}[] = {{")
        lines.extend(
            "    " + ", ".join(values[i : i + 8]) + ","
            for i in range(0, len(values), 8)
        )
        lines.append("};")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(
        f"Wrote {args.output}: {args.tokens} tokens, "
        f"{args.width}→{args.hidden}→{args.width}"
    )


if __name__ == "__main__":
    main()
