"""Run the array reference over a grid and write it for the model's tests.

Example:
    uv run python -m reef_perf.experiments.array_ref.main

Writes tests/cpp/matrix/FabricReference.inc, the table
MatrixFabricTest.ReferenceArrays checks getMacCost against, and
results/array_ref/reference.csv with the same rows.
"""

import argparse
import csv
import itertools
from pathlib import Path

from reef_perf.experiments.array_ref.ref import Array, measure
from reef_perf.sim import MODULE_ROOT

TABLE = MODULE_ROOT / "tests" / "cpp" / "matrix" / "FabricReference.inc"
"""The generated table the C++ test includes."""

CSV_OUT = MODULE_ROOT / "results" / "array_ref" / "reference.csv"
"""The same rows, for reading."""

SHAPES = (
    (16, 16, 4),  # int8 vtmmu: tk 4
    (16, 16, 2),  # bf16
    (16, 16, 1),  # fp32
    (4, 16, 4),
    (16, 4, 4),
    (8, 8, 4),
    (3, 5, 4),
    (1, 16, 4),
)
"""(M, N, K) per MAC: Zvt tiles are at most 16 x 16 x KMAX."""


def arrays() -> list[Array]:
    """The configurations checked: the presets and variations around them."""
    out: list[Array] = []
    for size, lanes, (row_op, col_op), hop, depth in itertools.product(
        (8, 16),
        (1, 4),
        (
            ("forwarded", "forwarded"),
            ("broadcast", "broadcast"),
            ("forwarded", "broadcast"),
            ("broadcast", "forwarded"),
        ),
        (1, 2),
        (1, 3),
    ):
        out.append(
            Array(
                size,
                size,
                lanes,
                "output",
                row_op,
                col_op,
                "in_place",
                hop=hop,
                depth=depth,
            )
        )
    for rows, cols, row_op, hop, load, double in itertools.product(
        (2, 4, 16),
        (8, 16),
        ("forwarded", "broadcast"),
        (1, 2),
        (0, 6),
        (False, True),
    ):
        out.append(
            Array(
                rows,
                cols,
                1,
                "weight",
                row_op,
                "forwarded",
                "chain",
                hop=hop,
                stationary_load_cycles=load,
                double_buffer=double,
            )
        )
    for rows, cols, lanes, level, double in itertools.product(
        (2, 8), (4, 8), (1, 4), (1, 2), (False, True)
    ):
        out.append(
            Array(
                rows,
                cols,
                lanes,
                "weight",
                "broadcast",
                "broadcast",
                "tree",
                tree_level=level,
                double_buffer=double,
            )
        )
    return out


def _cpp_row(a: Array, shape: tuple[int, int, int], r: dict[str, float]) -> str:
    enum = {
        "output": "Dataflow::Output",
        "weight": "Dataflow::Weight",
        "forwarded": "Delivery::Forwarded",
        "broadcast": "Delivery::Broadcast",
        "in_place": "Reduction::InPlace",
        "chain": "Reduction::Chain",
        "tree": "Reduction::Tree",
    }
    fields = [
        a.rows,
        a.cols,
        a.lanes,
        enum[a.dataflow],
        enum[a.row_operand],
        enum[a.col_operand],
        enum[a.reduction],
        a.hop,
        a.tree_level,
        a.depth,
        a.stationary_load_cycles,
        "true" if a.double_buffer else "false",
        *shape,
        int(r["latency"]),
        r["interval"],
    ]
    return "{" + ", ".join(str(f) for f in fields) + "},"


def main() -> None:
    """Measure every array and shape; write the C++ table and the CSV."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--table", type=Path, default=TABLE)
    parser.add_argument("--csv", type=Path, default=CSV_OUT)
    args = parser.parse_args()
    rows = []
    for a in arrays():
        for shape in SHAPES:
            rows.append((a, shape, measure(a, *shape)))
    lines = [
        "// Generated by python -m reef_perf.experiments.array_ref.main;",
        "// do not edit. Rows, cols, lanes, dataflow, row and column delivery,",
        "// reduction, hop, tree level, depth, stationary load cycles, double",
        "// buffer, M, N, K, then the reference's latency and back-to-back",
        "// interval (cycles; the interval may be fractional).",
        "// NOLINTBEGIN",
        *(_cpp_row(a, s, r) for a, s, r in rows),
        "// NOLINTEND",
    ]
    args.table.write_text("\n".join(lines) + "\n")
    args.csv.parent.mkdir(parents=True, exist_ok=True)
    with args.csv.open("w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(
            [
                "rows",
                "cols",
                "lanes",
                "dataflow",
                "row_operand",
                "col_operand",
                "reduction",
                "hop",
                "tree_level",
                "depth",
                "stationary_load_cycles",
                "double_buffer",
                "m",
                "n",
                "k",
                "latency",
                "interval",
            ]
        )
        for a, s, r in rows:
            w.writerow(
                [
                    a.rows,
                    a.cols,
                    a.lanes,
                    a.dataflow,
                    a.row_operand,
                    a.col_operand,
                    a.reduction,
                    a.hop,
                    a.tree_level,
                    a.depth,
                    a.stationary_load_cycles,
                    a.double_buffer,
                    *s,
                    r["latency"],
                    r["interval"],
                ]
            )
    print(f"wrote {args.table} and {args.csv}: {len(rows)} cases")


if __name__ == "__main__":
    main()
