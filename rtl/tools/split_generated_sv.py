"""Split a firtool CoralNPU .sv bundle back into its original files.

Usage: ``python3 tools/split_generated_sv.py BUNDLE.sv OUT_DIR FILELIST``.

firtool concatenates every output file into one .sv, each one after a line
``// ----- 8< ----- FILE "<path>" ----- 8< -----``. The chunk before the
first marker is the Chisel-generated top module itself.

Writes, with paths relative to ``rtl/``:

- ``OUT_DIR/<Top>.sv`` and every other design file (``*.sv``, ``*.v``,
  ``*.svh``), plus ``OUT_DIR/verification/`` (firtool assert, assume and
  cover layers, sim only).
- ``FILELIST``: the design files in compile order, one compilation unit.
- ``OUT_DIR/sim.f``: the same plus the verification layers.

Run from ``rtl/`` (tools/regen_coralnpu.sh does). Standard library only, so
it also runs outside the uv environment.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MARKER = re.compile(
    r'^// ----- 8< ----- FILE "(?P<path>[^"]+)" ----- 8< -----$'
)
HEADER = "// Generated by tools/split_generated_sv.py. Do not edit."


def split(bundle: Path) -> list[tuple[str, str]]:
    """Return the (path, text) chunks of a bundle, in bundle order."""
    chunks: list[tuple[str, list[str]]] = [(f"{bundle.stem}.sv", [])]
    for line in bundle.read_text().splitlines(keepends=True):
        m = MARKER.match(line.rstrip("\n"))
        if m:
            chunks.append((m["path"].removeprefix("./"), []))
        else:
            chunks[-1][1].append(line)
    paths = [p for p, _ in chunks]
    dups = sorted({p for p in paths if paths.count(p) > 1})
    if dups:
        msg = f"duplicate files in bundle: {dups}"
        raise ValueError(msg)
    return [(p, "".join(lines)) for p, lines in chunks]


def write_filelist(path: Path, out: Path, files: list[str], src: str) -> None:
    """Write a .f with an include dir and one file per line."""
    lines = [HEADER, f"// Source bundle: {src}", f"+incdir+{out}"]
    lines += [f"{out}/{f}" for f in files]
    path.write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    bundle, out, filelist = Path(args[0]), Path(args[1]), Path(args[2])

    design: list[str] = []
    verif: list[str] = []
    for path, text in split(bundle):
        dst = out / path
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text)
        # Headers stay in the filelist at their bundle position: fpnew uses
        # macros from registers.svh without including it, relying on the
        # bundle being one compilation unit. Include guards make the later
        # `include "rvv_backend*.svh" lines harmless.
        (verif if path.startswith("verification/") else design).append(path)

    # The top instantiates blackboxes (RstSync, RVV, FPU, Sram) that come
    # later in the bundle; packages go first for most tools.
    pkgs = [p for p in design if p.endswith("_pkg.sv")]
    order = pkgs + [p for p in design if p not in pkgs]
    write_filelist(filelist, out, order, bundle.name)
    write_filelist(out / "sim.f", out, order + verif, bundle.name)

    nhdr = sum(p.endswith(".svh") for p in design)
    print(
        f"{len(design) + len(verif)} files: {len(design) - nhdr} design,"
        f" {nhdr} headers, {len(verif)} verification -> {out}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
